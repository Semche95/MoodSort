#!/usr/bin/env bash
set -uo pipefail

input=$(cat)
cmd=$(jq -r '.tool_input.command // empty' <<<"$input")
[ -n "$cmd" ] || exit 0
root=${CLAUDE_PROJECT_DIR:-$(pwd)}

block() {
  printf 'Blocked by .claude/hooks/validate-bash.sh: %s\n' "$1" >&2
  exit 2
}

has() {
  grep -qiE -- "$1" <<<"$cmd"
}

sep='(^|[;&|(`[:space:]])'

has "${sep}sudo[[:space:]]" && block 'sudo is not allowed'
has "${sep}rm[[:space:]]+(-[a-zA-Z]+[[:space:]]+)*(/|~|\\\$HOME|\\*|\\.|\\./)([[:space:]]|$)" && block 'recursive removal of a root, home or whole directory'
has '(curl|wget)[^|]*\|[[:space:]]*(ba|z)?sh' && block 'piping a download into a shell'
has 'git[[:space:]]+push[^;&|]*[[:space:]](--force|--force-with-lease|-f)([[:space:]=]|$)' && block 'force push'
has 'git[[:space:]]+reset[^;&|]*--hard' && block 'git reset --hard discards uncommitted work'
has 'git[[:space:]]+clean[^;&|]*[[:space:]]-[a-zA-Z]*f' && block 'git clean -f deletes untracked files'

has '(git[[:space:]]+commit|gh[[:space:]]+(pr|release|issue))' \
  && has '(co-authored-by|noreply@anthropic\.com|generated with \[?claude)' \
  && block 'no Co-Authored-By or AI attribution in commits or PRs (AGENTS.md, Git)'

has "${sep}(vite|vite\\.js)[[:space:]]+build" && block 'no builds, they break the running pnpm dev (AGENTS.md, No autonomous builds)'
has "${sep}(pnpm|npm|yarn|bun)([[:space:]]+run)?[[:space:]]+build([[:space:]]|$|[;&|)])" && block 'no builds, they break the running pnpm dev (AGENTS.md, No autonomous builds)'
has "${sep}(pnpm|npm|yarn|bun)([[:space:]]+run)?[[:space:]]+dev([[:space:]]|$|[;&|)])" && block 'pnpm dev is already running on port 5170'
runs_atlas() {
  has "${sep}(pnpm|npm|yarn|bun)([[:space:]]+-[^[:space:];&|]+([[:space:]]+[^-[:space:];&|][^[:space:];&|]*)?)*([[:space:]]+run)?[[:space:]]+atlas([[:space:]]|$|[;&|)])" \
    || has "${sep}(node|bun|deno|tsx)[[:space:]][^;&|]*generate-atlas\\.mjs" \
    || has "(^|[;&|(\`])[[:space:]]*[^[:space:];&|]*generate-atlas\\.mjs"
}

# Expands $VAR and ${VAR} from literal or `mktemp -d /tmp/...` assignments made in the command itself; fails on anything else.
expand_vars() {
  local s=$1 name value re='\$\{?([A-Za-z_][A-Za-z0-9_]*)\}?'
  local literal="(\"[^\"\$]*\"|'[^']*'|[^[:space:]\"'\$;&|]+)"
  # Template without a slash after /tmp/, so the directory cannot leave /tmp.
  local tmp_dir='"?\$\(mktemp[[:space:]]+-d[[:space:]]+"?/tmp/([A-Za-z0-9._-]|\$\(basename[[:space:]]+"\$[A-Za-z_][A-Za-z0-9_]*"\))+"?\)"?'
  while [[ $s =~ $re ]]; do
    name=${BASH_REMATCH[1]}
    value=$(grep -E "(^|[;&|[:space:]])${name}=" <<<"$cmd" | tail -n 1 \
      | sed -E "s/^(.*[;&|[:space:]])?${name}=/${name}=/" \
      | grep -oE "^${name}=(${tmp_dir}|${literal})" | sed -E "s/^${name}=//")
    case "$value" in
      *'$(mktemp'*) value=/tmp/mktemp ;;
      *) value=$(sed -E "s/^[\"']//; s/[\"']$//" <<<"$value") ;;
    esac
    [ -n "$value" ] || return 1
    s=${s/"${BASH_REMATCH[0]}"/$value}
  done
  printf '%s' "$s"
}

# The generator writes next to its own script, so running it is only safe from a worktree under /tmp.
atlas_in_tmp_worktree() {
  local dir gen_at first_cd_at='' at target script
  dir=$(jq -r '.cwd // empty' <<<"$input")
  has "${sep}(pnpm|npm|yarn|bun)[[:space:]][^;&|]*(-C|--dir|--prefix|--cwd)([[:space:]=]|$)" && return 1
  while IFS= read -r script; do
    case "$script" in /* | '$'* | '~'*) return 1 ;; esac
  done < <(grep -oE "[^[:space:]\"';&|()]*generate-atlas\\.mjs" <<<"$cmd")
  gen_at=$(grep -boE "generate-atlas\\.mjs|[[:space:]]atlas([[:space:]]|$|[;&|)])" <<<"$cmd" | head -n 1 | cut -d: -f1)
  while IFS=: read -r at target; do
    [ -n "$first_cd_at" ] || first_cd_at=$at
    target=$(sed -E "s/^[;&|(\`[:space:]]*(cd|pushd)[[:space:]]*//; s/[\"']//g" <<<"$target")
    target=$(expand_vars "$target") || return 1
    case "$target" in
      /tmp/*) dir=$target ;;
      '' | -* | '~'* | /*) return 1 ;;
      *) dir="$dir/$target" ;;
    esac
    case "$dir" in /tmp/*) ;; *) return 1 ;; esac
  done < <(grep -boE "${sep}(cd|pushd)([[:space:]]+(\"[^\"]*\"|'[^']*'|[^;&|)[:space:]]+))?" <<<"$cmd")
  if [ -z "$first_cd_at" ] || [ "${gen_at:-0}" -lt "$first_cd_at" ]; then
    case "$(jq -r '.cwd // empty' <<<"$input")" in /tmp/*) ;; *) return 1 ;; esac
  fi
  case "$dir" in /tmp/*) return 0 ;; esac
  return 1
}

runs_atlas && ! atlas_in_tmp_worktree \
  && block 'the atlas is regenerated by pnpm dev, never by hand (allowed only in a review worktree under /tmp)'
has "${sep}rm[[:space:]][^;&|]*src/assets" && block 'never delete generated files under src/assets/'

has 'playwright[[:space:]]+install' && block 'no browser driver install, use the Playwright MCP server (AGENTS.md, Browser testing)'
has "${sep}(pnpm|npm|yarn|bun)[[:space:]]+(add|install|i)[[:space:]][^;&|]*(playwright|puppeteer|chromium|chromedriver|geckodriver|selenium)" && block 'no browser driver install, use the Playwright MCP server (AGENTS.md, Browser testing)'
has "${sep}(npx|pnpx|bunx|pnpm[[:space:]]+dlx)[[:space:]][^;&|]*(playwright|puppeteer)" && block 'no browser driver, use the Playwright MCP server (AGENTS.md, Browser testing)'
has "${sep}(pacman|yay|paru|apt|apt-get|brew|pip|pipx)[[:space:]][^;&|]*(chromium|chrome|firefox|playwright|puppeteer|geckodriver|chromedriver)" && block 'no browser install (AGENTS.md, Browser testing)'
has "${sep}(npx|pnpx|pnpm[[:space:]]+dlx)[[:space:]]+(--yes|-y)([[:space:]]|$)" && block 'no npx --yes package checks without approval (AGENTS.md, Filesystem scope)'

has "${sep}(locate|plocate|mlocate)[[:space:]]" && block 'no global filesystem search (AGENTS.md, Filesystem scope)'
has "${sep}\\.\\.(/|[[:space:]]|$|[;&|)])" && block 'stay inside the project directory (AGENTS.md, Filesystem scope)'
has "${sep}(find|ls|du|tree|cd|rm|chmod|chown)[[:space:]]+([^;&|]*[[:space:]])?/([[:space:]]|$|[;&|)])" && block 'stay inside the project directory (AGENTS.md, Filesystem scope)'

# Blanks quoted text, where ~ is never expanded, except the $( ) or `...` code inside it; unbalanced quotes keep the raw command.
unquoted() {
  local out='' stack='' c i end rest
  for ((i = 0; i < ${#cmd}; i++)); do
    c=${cmd:i:1}
    if [ "${cmd:i:2}" = '$(' ]; then stack+=c; out+='$('; ((i++)); continue; fi
    if [ "${stack: -1}" = d ]; then
      case "$c" in
        '\') ((i++)); out+=_ ;;
        '"') stack=${stack%d}; out+=_ ;;
        '`') stack+=b; out+=$c ;;
        *) out+=_ ;;
      esac
      continue
    fi
    if [ "$c" = '\' ]; then out+=$c${cmd:i+1:1}; ((i++)); continue; fi
    if [ "$c" = '`' ]; then
      if [ "${stack: -1}" = b ]; then stack=${stack%b}; else stack+=b; fi
    else
      case "$c" in
        "'")
          rest=${cmd:i+1}
          end=${rest%%"'"*}
          [ "$end" = "$rest" ] && { printf '%s' "$cmd"; return; }
          ((i += ${#end} + 1))
          out+=_
          continue
          ;;
        '"') stack+=d ;;
        '(') stack+=p ;;
        ')') case "${stack: -1}" in c | p) stack=${stack%?} ;; esac ;;
      esac
    fi
    out+=$c
  done
  if [ -n "$stack" ]; then printf '%s' "$cmd"; else printf '%s' "$out"; fi
}

# `=~ ` is the [[ ]] regex operator, not a home directory.
home=$(unquoted | sed -E 's/=~[[:space:]]/= /g' \
  | grep -oE "(^|[;&|(\`[:space:]=<>:])~([^[:space:];|&)<>]*)" | head -n 1 | sed -E "s/^[;&|(\`[:space:]=<>:]//")
[ -n "$home" ] && block "stay inside the project directory: $home (AGENTS.md, Filesystem scope)"

while IFS= read -r path; do
  path=$(sed -E "s/^[][;&|(\`[:space:]\"'=<>]//" <<<"$path")
  case "$path" in
    "$root" | "$root"/* | /tmp | /tmp/* | /dev/null | /dev/std* | /dev/fd/*) ;;
    '$HOME'*) block "stay inside the project directory: $path (AGENTS.md, Filesystem scope)" ;;
    /*)
      grep -qE '^/(usr|etc|home|root|var|opt|bin|sbin|lib|lib32|lib64|boot|srv|mnt|media|proc|sys|run|snap|nix|dev)(/|$)' <<<"$path" \
        && block "stay inside the project directory: $path (AGENTS.md, Filesystem scope)"
      ;;
  esac
done < <(grep -oE "(^|[;&|(\`[:space:]\"'=<>])(\\\$HOME|/)[^[:space:]\"';|&)<>]*" <<<"$cmd")

readers='(cat|head|tail|less|more|bat|sed|awk|grep|rg|xxd|od|strings|cut|sort|wc)'
forbidden='(node_modules/|dist/|src/assets/|pnpm-lock\.yaml|\.playwright-mcp/)'
exclusions="(:\\(exclude\\)|:!|:\\^|--exclude(-dir)?=|--glob[= ]+['\"]?!|-g[[:space:]]+['\"]?!)[^[:space:];&|]*"

reads_forbidden() {
  local prev='' tok seg
  while IFS= read -r tok; do
    case "$tok" in
      '||' | '&&' | ';' | '&' | '|') prev=$tok; continue ;;
    esac
    seg=$(sed -E "s/$exclusions//g" <<<"$tok")
    # A grep fed by a pipe reads stdin: the forbidden name is only its pattern.
    if ! { [ "$prev" = '|' ] && grep -qE '^[[:space:]]*(grep|rg)[[:space:]]' <<<"$seg"; }; then
      grep -qiE "${sep}${readers}[[:space:]][^;&|]*${forbidden}" <<<"$seg" && return 0
    fi
    prev=segment
  done < <(grep -oE '\|\||&&|[;&|]|[^;&|]+' <<<"$cmd")
  return 1
}

reads_forbidden && block 'never read node_modules/, dist/, src/assets/, pnpm-lock.yaml or .playwright-mcp/ (AGENTS.md, Token economy)'
has "(^|[[:space:]/\"'=<])\\.env(\\.(local|production|development|test)|\\.[a-z]+\\.local)?([[:space:]\"';|&)]|$)" && block 'never touch .env files, they may hold secrets'
has '(id_rsa|id_ed25519)([[:space:]"'"'"';|&)]|$)' && block 'never touch private keys'

# .pem/.key only count as key files when they exist or are globbed, so that properties like event.key pass.
while IFS= read -r keyfile; do
  case "$keyfile" in *'*'*) block "never touch private keys: $keyfile" ;; esac
  { [ -e "$keyfile" ] || [ -e "$root/$keyfile" ]; } && block "never touch private keys: $keyfile"
done < <(grep -oE "[^[:space:]\"';|&()<>=]+\\.(pem|key)([[:space:]\"';|&)]|$)" <<<"$cmd" | sed -E "s/[[:space:]\"';|&)]$//")

exit 0
